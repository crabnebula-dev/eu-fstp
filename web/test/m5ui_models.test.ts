// The read models and request bodies of the M5 post-grant screens
// (lanes L-UI1 and L-UI2; M5 design sections 5 and 6). The spellings
// are the ones `fstp-api-core` `grant.rs` writes and `forms.rs` reads.

import {
  decodeContract,
  decodeOverview,
  decodePayments,
  decodeQueue,
  decodeReports,
  decodeRedirect,
  advancedBody,
  canonicalBody,
  changeBody,
  closeBody,
  decideBody,
  determineBody,
  lineBody,
  paymentBody,
  reasonBody,
  reviewBody,
  signBody,
  parseClause,
} from "../src/grant/models.js";
import { assert, eq, test } from "./support/harness.js";

const REQUEST = {
  request: "7",
  proposal: "3",
  status: "UNDER_REVIEW",
  kind: "hardship",
  submission_checks: true,
  acceptance_checks: false,
  lines: [{ line: "8", milestone: "9", requested: "100.00", approved: "90.00" }],
};

/** R-NG-03: the overview shows the determination and the amounts the cell formatted. */
test("r_ng_03_overview_decodes_the_cell_reply_and_refuses_junk", () => {
  const o = decodeOverview({
    proposal: "3",
    state: "NEGOTIATION",
    determination: "4",
    amount: "1000.00",
    paid: "0.00",
    contract: null,
    requests: 0,
  });
  assert(o !== null, "a good overview");
  eq(o.determination, "4", "determination");
  eq(o.agreedPlan, null, "no plan member means none");
  eq(decodeOverview({ proposal: "x", state: "GRANTED" }), null, "an id that is not a decimal");
  eq(decodeOverview([]), null, "an array");
  eq(decodeOverview({ proposal: "3", state: "NEGOTIATION", determination: null, amount: null, paid: "1,00", contract: null, requests: 0 }), null, "a spelled amount outside ADR-006");
});

/** R-CT-04: open clause changes and the signature state of each party reach the page. */
test("r_ct_04_contract_view_decodes_versions_parties_and_open_changes", () => {
  const c = decodeContract({
    proposal: "3",
    contract: "5",
    status: "sent",
    versions: [
      {
        version: 1,
        state: "sent",
        parties: [{ field: "lead", role: "lead", signed: false, mine: true }],
        revisions: 1,
        digest: "00".repeat(32),
        open_changes: [2],
      },
    ],
  });
  assert(c !== null, "a good contract");
  eq(c.versions[0]?.open_changes[0], 2, "open change");
  eq(c.versions[0]?.parties[0]?.mine, true, "mine");
  const none = decodeContract({ proposal: "3", contract: null, status: null, versions: [] });
  assert(none !== null && none.contract === null, "not drafted yet");
  eq(decodeContract({ proposal: "3", contract: null, status: null, versions: [{ version: 1 }] }), null, "a partial version");
});

/** I-30: the digest of a signed version is shown as lowercase hex or not at all. */
test("i30_contract_digest_must_be_hex", () => {
  const v = { version: 1, state: "effective", parties: [], revisions: 2, digest: "zz", open_changes: [] };
  eq(decodeContract({ proposal: "3", contract: "5", status: "effective", versions: [v] }), null, "a digest that is not hex");
});

/** I-58 and I-32: a payment row carries its status and both check results, never a bank detail. */
test("i58_payment_rows_decode_with_checks_and_lines", () => {
  const rows = decodePayments([REQUEST]);
  assert(rows !== null, "rows");
  eq(rows[0]?.status, "UNDER_REVIEW", "status");
  eq(rows[0]?.lines[0]?.approved, "90.00", "approved");
  eq(decodePayments([{ ...REQUEST, status: "NOT_A_STATE" }]), null, "an unknown status");
  const q = decodeQueue([{ task: "release", request: REQUEST }]);
  assert(q !== null, "queue");
  eq(q[0]?.task, "release", "task");
  eq(decodeQueue([{ task: "steal", request: REQUEST }]), null, "an unknown task");
});

/** R-RP-03: a report row says whether the caller generated it, so the page can hold back Approve. */
test("r_rp_03_report_rows_decode", () => {
  const r = decodeReports([
    { report: "11", kind: "audit_file", call: "2", programme: null, document: "00".repeat(32), template: "t/1", generated_by_me: true, approved: false },
  ]);
  assert(r !== null, "reports");
  eq(r[0]?.generatedByMe, true, "generated by me");
  eq(decodeReports([{ report: "11" }]), null, "partial");
});

/** I-86: a redirect to the vault is a string the page checks before it navigates. */
test("i86_redirect_decodes_to_a_string_only", () => {
  eq(decodeRedirect({ redirect: "https://id.cell.example/w#ab" }), "https://id.cell.example/w#ab", "redirect");
  eq(decodeRedirect({ redirect: 3 }), null, "a number");
});

/** R-NG-03 and I-13: the determination names the agreed plan, each deduction its reason. */
test("r_ng_03_determination_body_names_plan_deductions_and_currency", () => {
  const ok = determineBody("12", [{ amount: "10.00", reason: "Synthetic ineligible cost" }]);
  assert(ok.ok, "accepted");
  eq(JSON.stringify(ok.value), '{"agreed":"12","currency":"EUR","deductions":[{"amount":"10.00","reason":"Synthetic ineligible cost"}]}', "body");
  assert(!determineBody("0x1", []).ok, "plan id is a decimal");
  assert(!determineBody("12", [{ amount: "1,5", reason: "x" }]).ok, "amount spelling");
  assert(!determineBody("12", [{ amount: "10.00", reason: " " }]).ok, "a deduction needs its reason");
});

/** R-CT-04: a clause change names a positive clause number and its text. */
test("r_ct_04_clause_change_bodies", () => {
  eq(parseClause("3"), 3, "clause");
  eq(parseClause("0"), null, "zero");
  eq(parseClause("-1"), null, "negative");
  eq(parseClause("1.5"), null, "fraction");
  eq(JSON.stringify(changeBody(2, "SYNTHETIC")), '{"clause":2,"text":"SYNTHETIC"}', "change");
  eq(JSON.stringify(decideBody(true)), '{"accept":true}', "decision");
});

/** P-30: the signature route is one of the three the cell knows, and the advanced route needs a reason. */
test("i30_signature_route_and_advanced_reason", () => {
  eq(JSON.stringify(signBody("wallet_qes")), '{"route":"wallet_qes"}', "wallet");
  const adv = advancedBody("lead", "Synthetic reason");
  assert(adv.ok, "advanced");
  assert(!advancedBody("lead", "  ").ok, "advanced without reason");
  eq(JSON.stringify(reasonBody("Because")), '{"reason":"Because"}', "reason");
  assert(reasonBody("  ") === null, "blank reason");
  assert(closeBody("done") !== null, "close");
});

/** R-PR-07 and I-58: a payment line names a milestone and an amount, evidence travels with it. */
test("i58_payment_body_lines", () => {
  const l = lineBody("9", "100.00", { location: "https://forge.example/synthetic/repo", release: "v1.0.0", licence: "MIT", report: "SYNTHETIC REPORT" });
  assert(l.ok, "line");
  const b = paymentBody([l.value]);
  eq(JSON.stringify(canonicalBody(b)), '{"currency":"EUR","kind":{"type":"Milestone"},"lines":[{"amount":"100.00","evidence":{"licence":"MIT","location":"https://forge.example/synthetic/repo","release":"v1.0.0","report":"SYNTHETIC REPORT"},"milestone":"9"}]}', "body");
  assert(!lineBody("9", "0", { location: "u", release: "r", licence: "MIT", report: "x" }).ok, "bare zero is not an ADR-006 amount");
  assert(!lineBody("", "1.00", { location: "u", release: "r", licence: "MIT", report: "x" }).ok, "milestone needed");
  assert(!lineBody("9", "1.00", { location: "", release: "r", licence: "MIT", report: "x" }).ok, "location needed");
});

/** I-32: the line review body carries the approved amount, and a reason when it is lower. */
test("i32_review_body", () => {
  eq(JSON.stringify(reviewBody("90.00", "Lower")), '{"approved":"90.00","currency":"EUR","reason":"Lower"}', "with reason");
  eq(JSON.stringify(reviewBody("100.00", "")), '{"approved":"100.00","currency":"EUR"}', "without");
});
