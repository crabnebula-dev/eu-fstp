//! TLS 1.3 over the internal runtime trait, using rustls with the aws-lc-rs provider (ADR-001).
//!
//! - TLS 1.3 only. The rustls `tls12` feature is off and the provider lists
//!   only TLS 1.3 cipher suites.
//! - The crypto provider is built explicitly from `rustls::crypto::aws_lc_rs`.
//!   X25519MLKEM768 is the preferred key exchange group, with classical
//!   groups kept for peers without hybrid support (see
//!   [`KEY_EXCHANGE_GROUPS`]).
//! - PEM input is parsed with `rustls-pki-types` under explicit
//!   [`PemLimits`].
//! - [`connect`] and [`accept`] run the handshake over any
//!   [`fstp_rt::Connection`], such as a tokio TCP stream or an in-memory
//!   duplex. The resulting [`TlsStream`] is itself a `Connection`.
//! - Mutual TLS for traffic between components (R-NF-09):
//!   [`ClientConfig::mutual`] presents a client certificate and
//!   [`ServerConfig::mutual`] requires one.
//! - External services: [`ClientConfig::public_roots`] trusts the Mozilla
//!   root set of webpki-roots (ADR-001 amendment of 2026-11-06) and always
//!   verifies the chain and the host name.
//! - Session resumption is allowed on both sides for less than
//!   [`MAX_RESUMPTION_AGE`] (one hour) after the full handshake that
//!   authenticated the session (policy P2). A chain of resumptions never
//!   extends that hour. After it, a full handshake validates every
//!   certificate again, so an expired certificate is rejected. The server
//!   keeps sessions in an in-house store and issues no stateless tickets.
//!
//! Test certificates live in `testdata/` next to this crate's manifest and
//! are regenerated by `testdata/gen.sh`.
//!
//! The fuzz project in `fuzz/` drives client and server handshakes against
//! hostile peers over an in-memory transport (TH-26, H-05). A third target
//! runs complete sessions between this crate's client and server, with
//! fuzzed IO timing, closes and faults.

