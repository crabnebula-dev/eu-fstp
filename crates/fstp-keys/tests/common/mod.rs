// ---------------------------------------------------------------------------
// Outcomes.

/// Why a call did not succeed.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Fail {
    /// A W0 stub refused with `NotImplemented`, or a test-side seam stands
    /// in for a call the stub lacks. Never a pass for a refusal test.
    Seam(String),
    /// The crate refused, with the error's `Debug` form.
    Refused(String),
}

impl std::fmt::Display for Fail {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Fail::Seam(s) => write!(f, "seam: {s}"),
            Fail::Refused(s) => write!(f, "refused: {s}"),
        }
    }
}

impl From<Fail> for String {
    fn from(f: Fail) -> String {
        f.to_string()
    }
}

/// Sorts an error of the crate. Every W0 stub error is a `NotImplemented`
/// variant, so its `Debug` form names it. Any other error is a refusal.
pub fn classify<E: std::fmt::Debug>(e: E) -> Fail {
    let shown = format!("{e:?}");
    if shown.starts_with("NotImplemented(") {
        Fail::Seam(shown)
    } else {
        Fail::Refused(shown)
    }
}

/// Passes only when `r` is a real refusal. An acceptance and a seam both
/// fail, each with its own message.
pub fn expect_refused<T: std::fmt::Debug>(r: Result<T, Fail>, what: &str) -> Result<(), String> {
    match r {
        Err(Fail::Refused(_)) => Ok(()),
        Err(Fail::Seam(s)) => Err(format!("{what}: seam: {s}")),
        Ok(v) => Err(format!("{what}: accepted {v:?}")),
    }
}

