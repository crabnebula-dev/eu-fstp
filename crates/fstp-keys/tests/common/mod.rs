// Envelope seams (design section 3.2).

/// The seam of the sealing helpers: the W0 stub of `fstp_keys::envelope`
/// has only the decoders and encoders. Design section 3.2 names
/// `seal_key`, `open_key`, `seal_blob`, `open_blob` and a `DataKey` type.
/// Lane W2f adds them, and these helpers then call them.
pub const ENVELOPE_SEAM: &str = "fstp_keys::envelope has no seal_key, open_key, seal_blob or open_blob and no DataKey type yet (design section 3.2, lane W2f)";

/// The seam of [`seal_blob_at_count`]: no `DataKey` exists that can be
/// imported with a seal count, as `fstp_crypto::aead::Key` can. Lane W2f
/// adds the count of ADR-004 part 1 ("fstp-keys counts every seal call
/// per key") and this helper then calls it.
pub const SEAL_COUNT_SEAM: &str = "fstp_keys has no DataKey that carries a seal count or can be imported at one (ADR-004 part 1 Seal-count limit, lane W2f)";

/// `fstp_keys::envelope::seal_key(pk, &DataKey::from(dek), ctx)`.
pub fn seal_key(
    pk: &HybridPublicKey,
    dek: &[u8; 32],
    ctx: &SealContext,
) -> Result<SealedKey, Fail> {
    let dek = envelope::DataKey::from_bytes(dek).map_err(classify)?;
    envelope::seal_key(pk, &dek, ctx).map_err(classify)
}

/// `fstp_keys::envelope::open_key(sk, sealed, ctx)`, as key bytes.
pub fn open_key(
    sk: &HybridSecretKey,
    sealed: &SealedKey,
    ctx: &SealContext,
) -> Result<[u8; 32], Fail> {
    envelope::open_key(sk, sealed, ctx)
        .map(|k| *k.expose())
        .map_err(classify)
}

/// `fstp_keys::envelope::seal_blob(&DataKey::from(dek), ctx, pt)`.
pub fn seal_blob(dek: &[u8; 32], ctx: &SealContext, pt: &[u8]) -> Result<SealedBlob, Fail> {
    let dek = envelope::DataKey::from_bytes(dek).map_err(classify)?;
    envelope::seal_blob(&dek, ctx, pt).map_err(classify)
}

/// `fstp_keys::envelope::open_blob(&DataKey::from(dek), ctx, blob)`, as
/// plain bytes.
pub fn open_blob(dek: &[u8; 32], ctx: &SealContext, blob: &SealedBlob) -> Result<Vec<u8>, Fail> {
    let dek = envelope::DataKey::from_bytes(dek).map_err(classify)?;
    envelope::open_blob(&dek, ctx, blob)
        .map(|pt| pt.to_vec())
        .map_err(classify)
}

/// Seals `pt` under the data key `dek` imported with `count` seals
/// already made.
pub fn seal_blob_at_count(
    dek: &[u8; 32],
    count: u64,
    ctx: &SealContext,
    pt: &[u8],
) -> Result<SealedBlob, Fail> {
    let dek = envelope::DataKey::from_bytes_with_count(dek, count).map_err(classify)?;
    envelope::seal_blob(&dek, ctx, pt).map_err(classify)
}

