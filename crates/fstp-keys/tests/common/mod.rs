// Seal contexts.

/// Every chain, in ADR-004 code order.
pub const CHAINS: [Chain; 5] = [
    Chain::App,
    Chain::Vault,
    Chain::CellBackup,
    Chain::ClusterBackup,
    Chain::ControlPlane,
];

/// Every purpose the W0 stub of `fstp_keys::Purpose` names.
pub const PURPOSES: [Purpose; 5] = [
    Purpose::Ledger,
    Purpose::Text,
    Purpose::AuditEvent,
    Purpose::Checkpoint,
    Purpose::Backup,
];

/// The ADR-004 part 1 chain code: App 1, Vault 2, CellBackup 3,
/// ClusterBackup 4, ControlPlane 5.
pub fn chain_code(chain: Chain) -> u8 {
    match chain {
        Chain::App => 1,
        Chain::Vault => 2,
        Chain::CellBackup => 3,
        Chain::ClusterBackup => 4,
        Chain::ControlPlane => 5,
    }
}

/// Sixteen generated bytes.
pub fn arr16(g: &mut Gen) -> [u8; 16] {
    let v = g.bytes(16..=16);
    let mut out = [0u8; 16];
    out.copy_from_slice(&v);
    out
}

/// Thirty-two generated bytes.
pub fn arr32(g: &mut Gen) -> [u8; 32] {
    let v = g.bytes(32..=32);
    let mut out = [0u8; 32];
    out.copy_from_slice(&v);
    out
}

/// A generated seal context.
pub fn gen_ctx(g: &mut Gen) -> SealContext {
    SealContext {
        cell: CellId(arr16(g)),
        chain: *g.pick(&CHAINS),
        purpose: *g.pick(&PURPOSES),
        group: GroupId(arr16(g)),
        generation: g.u32(),
        object: ObjectId(arr16(g)),
    }
}

/// Flips one generated byte of `a` to another value.
fn flip16(g: &mut Gen, a: [u8; 16]) -> [u8; 16] {
    let mut out = a;
    let at = g.usize_in(0..=15);
    out[at] ^= g.u8_in(1..=255);
    out
}

/// `ctx` with field `field` (0 cell, 1 chain, 2 purpose, 3 group,
/// 4 generation, 5 object) changed to another value.
pub fn moved_ctx(g: &mut Gen, ctx: &SealContext, field: usize) -> SealContext {
    let mut m = *ctx;
    match field {
        0 => m.cell = CellId(flip16(g, ctx.cell.0)),
        1 => {
            let others: Vec<Chain> = CHAINS.into_iter().filter(|c| *c != ctx.chain).collect();
            m.chain = *g.pick(&others);
        }
        2 => {
            let others: Vec<Purpose> = PURPOSES.into_iter().filter(|p| *p != ctx.purpose).collect();
            m.purpose = *g.pick(&others);
        }
        3 => m.group = GroupId(flip16(g, ctx.group.0)),
        4 => m.generation = ctx.generation ^ g.u32_in(1..=u32::MAX),
        _ => m.object = ObjectId(flip16(g, ctx.object.0)),
    }
    m
}

// ---------------------------------------------------------------------------
// The FSK1 bytes of ADR-004 part 1, written by hand.

/// Length of a sealed key header.
pub const HEADER_LEN: usize = 30;
/// Length of a sealed key: header, `E`, `ct_M`, nonce and wrapped key.
pub const SEALED_KEY_LEN: usize = HEADER_LEN + 32 + 1088 + 12 + 48;
/// Offset of the nonce in a sealed key.
pub const NONCE_AT: usize = HEADER_LEN + 32 + 1088;
/// Offset of `E` in a sealed key.
pub const E_AT: usize = HEADER_LEN;

/// The 30 header bytes of ADR-004 part 1 for `chain`, `group` and
/// `generation`: `"FSK1" | 1 | kem 1 | aead 1 | chain | group | generation`.
pub fn fsk1_header(chain: u8, group: [u8; 16], generation: u32) -> Vec<u8> {
    let mut out = Vec::with_capacity(HEADER_LEN);
    out.extend_from_slice(b"FSK1");
    out.push(1);
    out.extend_from_slice(&1u16.to_be_bytes());
    out.extend_from_slice(&1u16.to_be_bytes());
    out.push(chain);
    out.extend_from_slice(&group);
    out.extend_from_slice(&generation.to_be_bytes());
    out
}

/// A well-formed FSK1 sealed key with a generated header and generated
/// ciphertext, nonce and wrapped bytes. It opens under no key, but the
/// decoder must accept it, since every field holds an allowed value.
pub fn gen_fsk1(g: &mut Gen) -> Vec<u8> {
    let chain = g.u8_in(1..=5);
    let group = arr16(g);
    let generation = g.u32();
    let mut out = fsk1_header(chain, group, generation);
    out.extend_from_slice(&g.bytes(SEALED_KEY_LEN - HEADER_LEN..=SEALED_KEY_LEN - HEADER_LEN));
    out
}

