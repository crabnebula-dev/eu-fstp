//! Helpers shared by the `fstp-keys` crate tests (lane W2f, test author).
//!
//! Two kinds of helper live here.
//!
//! - **Builders and generators.** Seal contexts, the FSK1 bytes of ADR-004
//!   part 1 written by hand, and the M-SHRED universe of design section
//!   14.2 in production ids.
//! - **Test-side seams.** The W0 stub of `fstp-keys` lacks some calls the
//!   design names. Each helper below has the designed shape and returns
//!   [`Fail::Seam`] with the reason. Lane W2f replaces each body with one
//!   call into the crate, and the tests then check real behaviour. No
//!   helper stands in for production logic.
//!
//! [`Fail`] separates a refusal the crate means from a stub that refuses
//! everything. A refusal test passes only on [`Fail::Refused`], so no
//! `NotImplemented` stub and no seam can make it green.

#![allow(
    dead_code,
    unreachable_pub,
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::indexing_slicing,
    clippy::arithmetic_side_effects,
    reason = "test helpers; each test binary uses a subset"
)]

