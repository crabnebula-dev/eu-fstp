// The M-SHRED universe (design section 14.2), in production ids.

/// The group id of group `g`, as M-SHRED spells it.
pub fn group_id(g: u8) -> GroupId {
    GroupId([0x10_u8.saturating_add(g); 16])
}

/// The data key id of key `k`, as M-SHRED spells it.
pub fn dek_id(k: u8) -> DekId {
    DekId([0x20_u8.saturating_add(k); 16])
}

/// The data key groups of the universe: `g0 = {k0, k1}`, `g1 = {k2, k3}`.
pub const DATA_GROUPS: [(u8, [u8; 2]); 2] = [(0, [0, 1]), (1, [2, 3])];

/// The keyed digest group of the universe: `g2` digests `k0` and `k2`,
/// as a `Lookup` key digests two login emails (G24).
pub const DIGEST_GROUP: (u8, [u8; 2]) = (2, [0, 2]);

/// Every data key of the universe.
pub const KEYS: [u8; 4] = [0, 1, 2, 3];

/// The universe at epoch 1: two data key groups and one digest group.
pub fn universe() -> Result<ChainState, Fail> {
    let mut s = ChainState::genesis(Epoch(1));
    for (g, keys) in DATA_GROUPS {
        add_group(&mut s, group_id(g))?;
        for k in keys {
            admit(&mut s, group_id(g), dek_id(k))?;
        }
    }
    let (g, subjects) = DIGEST_GROUP;
    let subjects: Vec<DekId> = subjects.iter().map(|k| dek_id(*k)).collect();
    add_digest_group(&mut s, group_id(g), &subjects)?;
    Ok(s)
}

/// The groups a batch erasing `batch` replaces: every data key group that
/// holds a key of the batch, and the digest group when one of its subjects
/// is in the batch (design section 3.5, G24). In group order.
pub fn affected(batch: &BTreeSet<u8>) -> Vec<u8> {
    let mut out = Vec::new();
    for (g, keys) in DATA_GROUPS {
        if keys.iter().any(|k| batch.contains(k)) {
            out.push(g);
        }
    }
    let (g, subjects) = DIGEST_GROUP;
    if subjects.iter().any(|k| batch.contains(k)) {
        out.push(g);
    }
    out
}

/// The keys `Reseal` keeps in group `g` for `batch`: its members outside
/// the batch. A digest group holds no data key, so it keeps none.
pub fn keep(g: u8, batch: &BTreeSet<u8>) -> Vec<DekId> {
    DATA_GROUPS
        .iter()
        .filter(|(id, _)| *id == g)
        .flat_map(|(_, keys)| keys.iter())
        .filter(|k| !batch.contains(k))
        .map(|k| dek_id(*k))
        .collect()
}

/// The steps of ADR-004 part 2 for one rotation from epoch `old` that
/// erases `batch` from the universe. Step 2 is `NewGroups` and one
/// `Reseal` per affected group. Step 3 is `NewEpoch` and `RewrapGroups`,
/// and step 4 is `Commit`. Step 5 is `Snapshot` and `VerifySnapshot`.
/// Step 6 is `DestroyRoot` of the old epoch, and step 7 is `Complete`.
pub fn adr004_steps(old: u64, batch: &BTreeSet<u8>) -> Vec<Step> {
    let new = Epoch(old + 1);
    let hit = affected(batch);
    let mut steps = vec![Step::NewGroups {
        groups: hit.iter().map(|g| group_id(*g)).collect(),
    }];
    for g in &hit {
        steps.push(Step::Reseal {
            group: group_id(*g),
            keep: keep(*g, batch),
        });
    }
    steps.extend([
        Step::NewEpoch(new),
        Step::RewrapGroups(new),
        Step::Commit(new),
        Step::Snapshot(new),
        Step::VerifySnapshot(new),
        Step::DestroyRoot(Epoch(old)),
        Step::Complete {
            epoch: new,
            erased: batch.iter().map(|k| dek_id(*k)).collect(),
        },
    ]);
    steps
}

/// A generated non-empty batch of universe keys.
pub fn gen_batch(g: &mut Gen) -> BTreeSet<u8> {
    let mask = g.u8_in(1..=15);
    KEYS.into_iter().filter(|k| mask & (1 << k) != 0).collect()
}

/// The production ids of `batch`.
pub fn dek_ids(batch: &BTreeSet<u8>) -> BTreeSet<DekId> {
    batch.iter().map(|k| dek_id(*k)).collect()
}
