// The erasure planner (design section 3.5).

/// The seam of the admissions: the W0 `ChainState` has no call that adds
/// a data key group, admits a data key to a group, or adds a keyed digest
/// group with its subject data keys (M-SHRED `ADMIT_SEAM`). Lane W2f adds
/// them, and these helpers then call them.
pub const ADMIT_SEAM: &str = "fstp_keys::erasure::ChainState has no call that adds a data key group, admits a data key, or adds a keyed digest group with its subjects (design section 3.5, G24, lane W2f)";

/// The seam of [`request`]: `ChainState` has no call that records an
/// erasure request (M-SHRED `REQUEST_SEAM`).
pub const REQUEST_SEAM: &str = "fstp_keys::erasure::ChainState has no call that records an erasure request (design section 3.5 step 1, lane W2f)";

/// The seam of the state accessors: `ChainState` exposes its epoch, phase
/// and sizes only. Design section 3.4 needs the in-memory index to refuse
/// a key under erasure, and the tests need a group's generation and a
/// root's state.
pub const ACCESSOR_SEAM: &str = "fstp_keys::erasure::ChainState exposes no group generation, root state or open refusal of a data key (design sections 3.4 and 3.5, lane W2f)";

/// Adds a data key group at its first generation.
pub fn add_group(s: &mut ChainState, group: GroupId) -> Result<(), Fail> {
    s.add_group(group).map_err(classify)
}

/// Admits a data key to the current generation of `group`.
pub fn admit(s: &mut ChainState, group: GroupId, dek: DekId) -> Result<(), Fail> {
    s.admit(group, dek).map_err(classify)
}

/// Adds a keyed digest group (`Lookup`, `CredLookup` or `Match`) that
/// digests the plaintext of `subjects` (G24).
pub fn add_digest_group(
    s: &mut ChainState,
    group: GroupId,
    subjects: &[DekId],
) -> Result<(), Fail> {
    s.add_digest_group(group, subjects).map_err(classify)
}

/// Step 1: records an erasure request for `dek` at ledger sequence `seq`.
pub fn request(s: &mut ChainState, dek: DekId, seq: u64) -> Result<(), Fail> {
    s.request(dek, seq).map_err(classify)
}

/// Whether the in-memory index refuses to open `dek` (design section 3.4).
pub fn refused_for_open(s: &ChainState, dek: DekId) -> Result<bool, Fail> {
    Ok(s.refused_for_open(dek))
}

/// The committed generation of `group`.
pub fn generation(s: &ChainState, group: GroupId) -> Result<u32, Fail> {
    s.generation(group)
        .ok_or_else(|| Fail::Refused(format!("no group {group:?}")))
}

/// The state of root epoch `e`, if the chain knows it.
pub fn root_state(s: &ChainState, e: Epoch) -> Result<Option<RootState>, Fail> {
    Ok(s.root_state(e))
}

/// `fstp_keys::erasure::plan_erasure`, as its steps. The design gives it
/// an infallible signature and the W0 stub a `Result`. Only this helper
/// changes when lane W2f restores the designed one.
pub fn plan(s: &ChainState, batch: &BTreeSet<DekId>) -> Result<Vec<Step>, Fail> {
    erasure::plan_erasure(s, batch)
        .map(|p| p.steps)
        .map_err(classify)
}

/// `fstp_keys::erasure::next`. As [`plan`], only this helper changes when
/// the designed infallible signature returns.
pub fn next_step(s: &ChainState) -> Result<Option<Step>, Fail> {
    erasure::next(s).map_err(classify)
}

/// `fstp_keys::erasure::apply`.
pub fn apply_step(s: &mut ChainState, step: &Step) -> Result<(), Fail> {
    erasure::apply(s, step).map_err(classify)
}

/// The most steps one drive takes before it reports a planner that never
/// goes idle. A run of the universe has at most 13 steps.
pub const DRIVE_LIMIT: usize = 256;

/// Drives the chain through `next` and `apply` until `next` answers
/// `None`, and returns the steps in order.
pub fn drive(s: &mut ChainState) -> Result<Vec<Step>, Fail> {
    let mut done = Vec::new();
    while let Some(step) = next_step(s)? {
        if done.len() >= DRIVE_LIMIT {
            return Err(Fail::Refused(format!(
                "the planner gave more than {DRIVE_LIMIT} steps: {done:?}"
            )));
        }
        apply_step(s, &step)?;
        done.push(step);
    }
    Ok(done)
}

