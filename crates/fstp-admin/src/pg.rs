//! The two PostgreSQL clusters of a host (ADR-028 "PostgreSQL",
//! "Database provisioning" and "Migrations", ADR-005, ADR-011, I-82,
//! I-83).
//!
//! Each cluster is created by `initdb` with the superuser `fstp_super`,
//! listens on loopback only with TLS 1.3, and starts with a `pg_hba.conf`
//! that admits only the superuser and the replication role over
//! verified TLS. Every provisioning job then runs through
//! `fstp-pgagent run-job`, the agent's own executor with its typed jobs:
//! `harden`, `create-database`, `create-roles`, `revocations`,
//! `write-hba` and `grants`. `fstp-admin` itself renders no DDL beyond
//! the login passwords, the migrations and the placement row, as the
//! world harness does.

use std::io::Write as _;
use std::net::{IpAddr, Ipv4Addr};
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use fstp_pki::cert::CertKind;

use crate::config::Services;
use crate::layout::{Cluster, Layout};
use crate::pki::{Ca, Leaf, PkiFail, random_hex, write_pair};
use crate::state::{State, write_atomic};
use crate::svc::{Ready, RunFail, Service};

/// The superuser of every cluster (`fstp_control::pg::HBA_SUPERUSER_LINE`).
pub const SUPERUSER: &str = "fstp_super";

/// The first `pg_hba.conf` of a cluster: the superuser and replication
/// lines and the reject lines of `fstp_control::pg::render_hba`, before
/// the agent's `write-hba` job adds the cell's lines. A celltest ties
/// this text to the renderer.
pub const INITIAL_HBA: &str = "# Generated by fstp_control::pg::render_hba. Do not edit.\n\
hostssl all fstp_super 127.0.0.1/32 scram-sha-256 clientcert=verify-full\n\
hostssl replication fstp_repl 127.0.0.1/32 scram-sha-256 clientcert=verify-full\n\
local all all reject\n\
host all all 0.0.0.0/0 reject\n\
host all all ::/0 reject\n";

/// Why a database step failed.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum PgFail {
    /// A command failed.
    Run(RunFail),
    /// A certificate failed.
    Pki(PkiFail),
    /// `fstp-pgagent run-job` refused or failed a job: the job word.
    Job(&'static str),
    /// A SQL step failed. It names what ran, never a literal.
    Sql(&'static str),
    /// A migration file failed: the cluster and the version.
    Migration(&'static str, u32),
    /// The migration directory is missing or malformed.
    Migrations(PathBuf),
    /// A file did not read or write.
    Io,
}

impl From<std::io::Error> for PgFail {
    fn from(_: std::io::Error) -> PgFail {
        PgFail::Io
    }
}
impl From<RunFail> for PgFail {
    fn from(e: RunFail) -> PgFail {
        PgFail::Run(e)
    }
}
impl From<PkiFail> for PgFail {
    fn from(e: PkiFail) -> PgFail {
        PgFail::Pki(e)
    }
}

/// The cell database of `c`.
#[must_use]
pub fn dbname(c: Cluster, cell: &[u8; 16]) -> String {
    format!("{}_{}", c.prefix(), crate::pki::hex(cell))
}

/// The role suffixes of a cluster's cell database, in the plan's order
/// (`fstp_control::pg::roles_of`, ADR-011).
#[must_use]
pub fn role_suffixes(c: Cluster) -> &'static [&'static str] {
    match c {
        Cluster::App => &["migrator", "writer", "app", "keys", "auditor"],
        Cluster::Vault => &["migrator", "vault", "keys"],
    }
}

/// The login role `<database>_<suffix>`.
#[must_use]
pub fn role(c: Cluster, cell: &[u8; 16], suffix: &str) -> String {
    format!("{}_{suffix}", dbname(c, cell))
}

/// The roles a service logs in as: the credential stem of each, which is
/// also its role suffix.
#[must_use]
pub fn service_logins(c: Cluster) -> &'static [&'static str] {
    match c {
        Cluster::App => &["writer", "app", "keys"],
        Cluster::Vault => &["vault", "keys"],
    }
}

/// The data directory owner in systemd mode.
pub const PG_USER: &str = "postgres";

fn as_pg_user(layout: &Layout, program: &Path) -> Command {
    crate::stack::as_user(layout, PG_USER, program)
}

fn chown_pg(layout: &Layout, path: &Path) -> Result<(), PgFail> {
    if layout.cfg.services == Services::Systemd {
        let mut c = Command::new("chown");
        c.arg("-R").arg(format!("{PG_USER}:{PG_USER}")).arg(path);
        crate::svc::run_ok(&mut c, &crate::svc::Manager::new(layout).log())?;
    }
    Ok(())
}

/// The service of a cluster.
#[must_use]
pub fn service(layout: &Layout, c: Cluster) -> Service {
    Service {
        name: format!("fstp-postgres-{}", c.name()),
        what: match c {
            Cluster::App => "application database",
            Cluster::Vault => "vault database",
        },
        program: layout.pg_bin("postgres"),
        args: vec!["-D".into(), layout.pg_data(c).into_os_string()],
        env: Vec::new(),
        user: Some(PG_USER.to_owned()),
        unit_lines: vec!["KillMode=mixed".into(), "KillSignal=SIGINT".into()],
        direct_credentials: None,
        ready: Ready::Tcp(std::net::SocketAddr::new(
            IpAddr::V4(Ipv4Addr::LOCALHOST),
            layout.pg_port(c),
        )),
        after: Vec::new(),
    }
}

/// The lines `setup` appends to `postgresql.conf`.
#[must_use]
pub fn conf(layout: &Layout, c: Cluster) -> String {
    let tls = layout.pg_data(c).join("tls");
    format!(
        "\n# Written by fstp-admin (ADR-028). Edit /etc/fstp/fstp.json instead.\n\
         listen_addresses = '127.0.0.1'\n\
         port = {port}\n\
         unix_socket_directories = ''\n\
         ssl = on\n\
         ssl_cert_file = '{cert}'\n\
         ssl_key_file = '{key}'\n\
         ssl_ca_file = '{ca}'\n\
         ssl_min_protocol_version = 'TLSv1.3'\n\
         password_encryption = 'scram-sha-256'\n\
         wal_level = replica\n\
         max_wal_senders = 4\n\
         wal_keep_size = '256MB'\n",
        port = layout.pg_port(c),
        cert = tls.join("server.pem").display(),
        key = tls.join("server.key").display(),
        ca = tls.join("ca.pem").display(),
    )
}

/// The issued server certificate of a cluster: CN `127.0.0.1`, the
/// cluster kind as OU (I-83).
///
/// # Errors
///
/// [`PgFail::Pki`] when it does not issue.
pub fn server_leaf(ca: &Ca, c: Cluster) -> Result<crate::pki::Issued, PgFail> {
    Ok(ca.issue(&Leaf {
        cn: "127.0.0.1",
        ou: Some(c.kind()),
        kind: CertKind::Server,
        dns: &["localhost"],
        ips: &[IpAddr::V4(Ipv4Addr::LOCALHOST)],
    })?)
}

/// Creates the cluster `c` with `initdb` when its data directory holds
/// none, with its TLS files, its configuration and its first
/// `pg_hba.conf`. Returns the SHA-256 of the new server certificate's
/// SPKI, or `None` when the cluster existed.
///
/// # Errors
///
/// [`PgFail`] for a failed command or file.
pub fn init_cluster(layout: &Layout, c: Cluster, ca: &Ca) -> Result<Option<[u8; 32]>, PgFail> {
    let data = layout.pg_data(c);
    let dir = layout.pg_dir(c);
    std::fs::create_dir_all(&dir)?;
    if data.join("PG_VERSION").is_file() {
        return Ok(None);
    }
    std::fs::create_dir_all(&data)?;
    {
        use std::os::unix::fs::PermissionsExt as _;
        std::fs::set_permissions(&data, std::fs::Permissions::from_mode(0o700))?;
    }
    chown_pg(layout, &data)?;
    let password = random_hex(24)?;
    write_atomic(&dir.join("super.password"), password.as_bytes(), 0o600)?;
    let pwfile = data.with_extension("pwfile");
    write_atomic(&pwfile, password.as_bytes(), 0o600)?;
    chown_pg(layout, &pwfile)?;
    let log = crate::svc::Manager::new(layout).log();
    let mut init = as_pg_user(layout, &layout.pg_bin("initdb"));
    init.arg("-D")
        .arg(&data)
        .arg("-U")
        .arg(SUPERUSER)
        .arg("--auth=scram-sha-256")
        .arg(format!("--pwfile={}", pwfile.display()))
        .arg("--encoding=UTF8")
        .arg("--locale=C")
        .arg("--no-instructions");
    let done = crate::svc::run_ok(&mut init, &log);
    let _ = std::fs::remove_file(&pwfile);
    done?;
    let tls = data.join("tls");
    std::fs::create_dir_all(&tls)?;
    let server = server_leaf(ca, c)?;
    write_pair(&tls, "server.pem", "server.key", &server)?;
    write_atomic(&tls.join("ca.pem"), &ca.pem, 0o600)?;
    write_atomic(&dir.join("ca.pem"), &ca.pem, 0o600)?;
    issue_super(layout, c, ca)?;
    let mut conf_text = std::fs::read_to_string(data.join("postgresql.conf"))?;
    conf_text.push_str(&conf(layout, c));
    write_atomic(&data.join("postgresql.conf"), conf_text.as_bytes(), 0o600)?;
    write_atomic(&data.join("pg_hba.conf"), INITIAL_HBA.as_bytes(), 0o600)?;
    chown_pg(layout, &data)?;
    Ok(Some(server.spki_sha256))
}

/// Issues the superuser's client certificate again, for `psql` and for
/// the agent.
///
/// # Errors
///
/// [`PgFail`] for a failed certificate or file.
pub fn issue_super(layout: &Layout, c: Cluster, ca: &Ca) -> Result<(), PgFail> {
    let dir = layout.pg_dir(c);
    let cert = ca.issue(&Leaf {
        cn: SUPERUSER,
        ou: None,
        kind: CertKind::Client,
        dns: &[],
        ips: &[],
    })?;
    write_pair(&dir, "super.pem", "super.key", &cert)?;
    Ok(())
}

/// The agent's configuration file of `c`.
#[must_use]
pub fn agent_config(layout: &Layout, c: Cluster) -> PathBuf {
    layout.config_file(&format!("pgagent-{}", c.name()))
}

/// Writes the agent's configuration and credentials of `c`. The agent
/// never listens on a single host, but its configuration names a
/// listener and its certificate, so they are issued from the tunnel CA.
///
/// # Errors
///
/// [`PgFail`] for a failed certificate or file.
pub fn write_agent(
    layout: &Layout,
    c: Cluster,
    cluster_ca: &Ca,
    tunnel_ca: &Ca,
) -> Result<(), PgFail> {
    let creds = layout.creds(&format!("pgagent-{}", c.name()));
    std::fs::create_dir_all(&creds)?;
    let su = layout.pg_dir(c);
    for (from, to) in [
        ("super.pem", "fstp_super.pem"),
        ("super.key", "fstp_super-key.pem"),
        ("super.password", "fstp_super.password"),
    ] {
        let b = std::fs::read(su.join(from))?;
        write_atomic(&creds.join(to), &b, 0o600)?;
    }
    write_atomic(&creds.join("cluster-ca.pem"), &cluster_ca.pem, 0o600)?;
    write_atomic(&creds.join("control-ca.pem"), &tunnel_ca.pem, 0o600)?;
    if crate::pki::needs_issue(&creds.join("pgagent.pem")) {
        let l = tunnel_ca.issue(&Leaf {
            cn: "pgagent",
            ou: None,
            kind: CertKind::Server,
            dns: &["localhost"],
            ips: &[IpAddr::V4(Ipv4Addr::LOCALHOST)],
        })?;
        write_pair(&creds, "pgagent.pem", "pgagent-key.pem", &l)?;
    }
    let listen_port = layout.pg_port(c).saturating_add(2);
    let text = format!(
        "{{\"cell_subnet\":\"127.0.0.1/32\",\"cluster_kind\":\"{}\",\"credentials_dir\":{},\"hba_file\":{},\"listen\":\"127.0.0.1:{listen_port}\",\"postgres_port\":{}}}\n",
        c.kind(),
        crate::config::quote(&creds.display().to_string()),
        crate::config::quote(&layout.pg_data(c).join("pg_hba.conf").display().to_string()),
        layout.pg_port(c),
    );
    write_atomic(&agent_config(layout, c), text.as_bytes(), 0o600)?;
    chown_pg(layout, &creds)?;
    chown_pg(layout, &agent_config(layout, c))?;
    Ok(())
}

/// Runs `fstp-pgagent run-job <words>` for cluster `c`, as the
/// `postgres` user in systemd mode, since `write-hba` replaces a file of
/// the data directory.
///
/// # Errors
///
/// [`PgFail::Job`] naming the job when it fails or is refused.
pub fn job(
    layout: &Layout,
    c: Cluster,
    word: &'static str,
    db: Option<&str>,
) -> Result<(), PgFail> {
    let mut cmd = as_pg_user(layout, &layout.bin("fstp-pgagent"));
    cmd.env("FSTP_PGAGENT_CONFIG", agent_config(layout, c))
        .arg("run-job")
        .arg(word);
    if let Some(d) = db {
        cmd.arg(d);
    }
    match crate::svc::run_logged(&mut cmd, &crate::svc::Manager::new(layout).log())? {
        Some(0) => Ok(()),
        _ => Err(PgFail::Job(word)),
    }
}

/// Appends the archive settings to the cluster's configuration, once.
/// Returns whether it changed the file, so the cluster needs a restart.
///
/// # Errors
///
/// [`PgFail::Io`] when the file does not read or write.
pub fn enable_archive(layout: &Layout, c: Cluster, backup_config: &Path) -> Result<bool, PgFail> {
    let path = layout.pg_data(c).join("postgresql.conf");
    let mut text = std::fs::read_to_string(&path)?;
    if text.contains("archive_mode = on") {
        return Ok(false);
    }
    text.push_str(&format!(
        "archive_mode = on\narchive_timeout = 60\narchive_command = 'FSTP_BACKUP_CONFIG={} {} wal-archive %p %f'\n",
        backup_config.display(),
        layout.bin("fstp-backup").display()
    ));
    write_atomic(&path, text.as_bytes(), 0o600)?;
    chown_pg(layout, &path)?;
    Ok(true)
}

/// Runs `sql` in `db` on cluster `c` as the superuser, over TLS with its
/// client certificate (`HBA_SUPERUSER_LINE`), and returns the output.
///
/// # Errors
///
/// [`PgFail::Sql`] naming `what` when psql fails.
pub fn psql(
    layout: &Layout,
    c: Cluster,
    db: &str,
    sql: &str,
    what: &'static str,
) -> Result<String, PgFail> {
    let dir = layout.pg_dir(c);
    let password = std::fs::read_to_string(dir.join("super.password"))?;
    let port = layout.pg_port(c);
    let passfile = dir.join("pgpass");
    write_atomic(
        &passfile,
        format!("127.0.0.1:{port}:*:{SUPERUSER}:{}\n", password.trim()).as_bytes(),
        0o600,
    )?;
    let mut cmd = Command::new(layout.pg_bin("psql"));
    cmd.args(["-X", "-q", "-A", "-t", "-v", "ON_ERROR_STOP=1", "-f", "-"])
        .env("PGHOST", "127.0.0.1")
        .env("PGPORT", port.to_string())
        .env("PGUSER", SUPERUSER)
        .env("PGDATABASE", db)
        .env("PGSSLMODE", "verify-full")
        .env("PGSSLROOTCERT", dir.join("ca.pem"))
        .env("PGSSLCERT", dir.join("super.pem"))
        .env("PGSSLKEY", dir.join("super.key"))
        .env("PGPASSFILE", &passfile)
        .env("PGCONNECT_TIMEOUT", "10")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped());
    let mut child = cmd.spawn().map_err(|_| PgFail::Sql(what))?;
    if let Some(mut stdin) = child.stdin.take() {
        stdin
            .write_all(sql.as_bytes())
            .map_err(|_| PgFail::Sql(what))?;
    }
    let out = child.wait_with_output().map_err(|_| PgFail::Sql(what))?;
    if !out.status.success() {
        // The log gets psql's message, except for the statements that
        // hold a password, since psql may echo the failing line.
        let log = crate::svc::Manager::new(layout).log();
        if let Ok(mut f) = std::fs::OpenOptions::new()
            .create(true)
            .append(true)
            .open(&log)
        {
            let _ = f.write_all(format!("psql failed: {what}\n").as_bytes());
            if what != "the login roles" {
                let _ = f.write_all(&out.stderr);
            }
        }
        return Err(PgFail::Sql(what));
    }
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_owned())
}

/// Provisions the cell database of `c` (design section 9.2 steps 4 to 7):
/// roles with passwords, the database with CONNECT for its roles, the
/// agent's jobs, the migrations as the migrator, the placement row and
/// the grants. Each part checks first, so a re-run only adds what is new.
/// The service logins' passwords are written to `creds` as
/// `<stem>.password`, and kept on a re-run.
///
/// # Errors
///
/// [`PgFail`] naming the part that failed.
pub fn provision(
    layout: &Layout,
    state: &mut State,
    c: Cluster,
    cell: &[u8; 16],
    creds: &Path,
) -> Result<(), PgFail> {
    let name = dbname(c, cell);
    if !state.done(&format!("harden-{}", c.name())) {
        job(layout, c, "harden", None)?;
        state.mark(&format!("harden-{}", c.name()))?;
    }
    // Roles: each with LOGIN and a password. A service's password is
    // kept in its credentials directory; the others stay unknown.
    let mut sql = String::new();
    for suffix in role_suffixes(c) {
        let rn = role(c, cell, suffix);
        let password = if service_logins(c).contains(suffix) {
            let file = creds.join(format!("{suffix}.password"));
            match std::fs::read_to_string(&file) {
                Ok(p) if !p.trim().is_empty() => p.trim().to_owned(),
                _ => {
                    let p = random_hex(24)?;
                    write_atomic(&file, p.as_bytes(), 0o600)?;
                    p
                }
            }
        } else {
            random_hex(24)?
        };
        // The role name follows the ADR-011 grammar and the password is
        // hex, so neither needs quoting beyond the identifier quotes.
        sql.push_str(&format!(
            "DO $$BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{rn}') THEN \
             CREATE ROLE \"{rn}\" LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD '{password}'; \
             ELSE ALTER ROLE \"{rn}\" LOGIN PASSWORD '{password}'; END IF; END$$;\n"
        ));
    }
    psql(layout, c, "postgres", &sql, "the login roles")?;
    let exists = psql(
        layout,
        c,
        "postgres",
        &format!("SELECT count(*) FROM pg_database WHERE datname = '{name}';"),
        "the database check",
    )? == "1";
    if !exists {
        let mut sql = format!(
            "CREATE DATABASE \"{name}\";\nREVOKE CONNECT, TEMPORARY ON DATABASE \"{name}\" FROM PUBLIC;\n"
        );
        for suffix in role_suffixes(c) {
            sql.push_str(&format!(
                "GRANT CONNECT ON DATABASE \"{name}\" TO \"{}\";\n",
                role(c, cell, suffix)
            ));
        }
        psql(layout, c, "postgres", &sql, "the cell database")?;
    }
    if !state.done(&format!("jobs-{}", c.name())) {
        for word in ["create-database", "create-roles", "revocations"] {
            job(layout, c, word, Some(&name))?;
        }
        job(layout, c, "write-hba", None)?;
        state.mark(&format!("jobs-{}", c.name()))?;
    }
    let migrator = role(c, cell, "migrator");
    let applied = migrate(layout, state, c, &name, &migrator)?;
    if !state.done(&format!("placement-{}", c.name())) {
        let cluster_id = match state.get(&format!("cluster.{}", c.name())) {
            Some(id) => id.to_owned(),
            None => {
                let id = random_hex(16)?;
                state.set(&format!("cluster.{}", c.name()), &id)?;
                id
            }
        };
        let kind = match c {
            Cluster::App => 1,
            Cluster::Vault => 2,
        };
        psql(
            layout,
            c,
            &name,
            &format!(
                "SET ROLE \"{migrator}\";\nINSERT INTO fstp_meta.placement (cell_id, cluster_id, kind) \
                 SELECT '\\x{}'::bytea, '\\x{cluster_id}'::bytea, {kind} \
                 WHERE NOT EXISTS (SELECT 1 FROM fstp_meta.placement);\n",
                crate::pki::hex(cell)
            ),
            "the placement row",
        )?;
        state.mark(&format!("placement-{}", c.name()))?;
    }
    if applied > 0 || !state.done(&format!("grants-{}", c.name())) {
        job(layout, c, "grants", Some(&name))?;
        state.mark(&format!("grants-{}", c.name()))?;
    }
    Ok(())
}

/// The migration files of `dir`, as `(version, path)` in order. A file is
/// `NNNN_name.sql`.
///
/// # Errors
///
/// [`PgFail::Migrations`] when the directory does not read, holds a
/// malformed name, or repeats or skips a version.
pub fn migration_files(dir: &Path) -> Result<Vec<(u32, PathBuf)>, PgFail> {
    let bad = || PgFail::Migrations(dir.to_owned());
    let mut out = Vec::new();
    for e in std::fs::read_dir(dir).map_err(|_| bad())? {
        let p = e.map_err(|_| bad())?.path();
        let Some(name) = p.file_name().and_then(|n| n.to_str()) else {
            return Err(bad());
        };
        let Some(stem) = name.strip_suffix(".sql") else {
            continue;
        };
        let (num, rest) = stem.split_once('_').ok_or_else(bad)?;
        if num.len() != 4 || rest.is_empty() {
            return Err(bad());
        }
        let v: u32 = num.parse().map_err(|_| bad())?;
        out.push((v, p));
    }
    out.sort();
    for (i, (v, _)) in out.iter().enumerate() {
        if u32::try_from(i).ok().and_then(|i| i.checked_add(1)) != Some(*v) {
            return Err(bad());
        }
    }
    if out.is_empty() {
        return Err(bad());
    }
    Ok(out)
}

/// Runs the migration files after the version the state records, each in
/// a session of its own as `migrator`, and records each. Returns how many
/// ran.
///
/// # Errors
///
/// [`PgFail::Migration`] naming the version that failed.
pub fn migrate(
    layout: &Layout,
    state: &mut State,
    c: Cluster,
    db: &str,
    migrator: &str,
) -> Result<u32, PgFail> {
    let key = format!("migrated.{}", c.name());
    let done: u32 = state.get(&key).and_then(|v| v.parse().ok()).unwrap_or(0);
    let mut ran = 0u32;
    for (v, path) in migration_files(&layout.migrations(c))? {
        if v <= done {
            continue;
        }
        let sql = std::fs::read_to_string(&path)?;
        psql(
            layout,
            c,
            db,
            &format!("SET ROLE \"{migrator}\";\n{sql}"),
            "a migration",
        )
        .map_err(|_| PgFail::Migration(c.name(), v))?;
        state.set(&key, &v.to_string())?;
        ran = ran.saturating_add(1);
    }
    Ok(ran)
}

